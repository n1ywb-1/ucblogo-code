Module.runjs = (expr) => {
    if (typeof document === 'undefined') return;
    let r;
    try {
        r = eval(expr);
    }
    catch (error) {
        r = error.toString();
        console.error(error);
        window.alert(r);
    }
    if (r instanceof Promise) {
        r.then(r2 => Module.FS_runjs_getChar_buffer_append_obj(r2)).catch(window.alert)
    }
    else {
        Module.FS_runjs_getChar_buffer_append_obj(r);
    }
};
